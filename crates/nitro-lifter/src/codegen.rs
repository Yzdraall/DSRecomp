use std::fmt::Write;

use nitro_arm::{
    AddrOffset, ArmOp, Cond, CpuMode, DecodedInst, EdgeKind, FunctionUnit, MemSize, ModuleCfg,
    ShiftOp, ShiftedOp2,
};

const FUNCTIONS_PER_SHARD: usize = 150;

/// Generated Rust source files for a single module (`static_arm9` or `ov_N`).
#[derive(Debug, Clone)]
pub struct GeneratedModuleFiles {
    /// `(filename, rust_source)` pairs under `src/generated/`
    pub files: Vec<(String, String)>,
    pub mod_stem: String,
    pub function_count: usize,
    pub block_count: usize,
}

/// Emits `#![forbid(unsafe_code)]`-clean Rust modules for a `ModuleCfg`.
pub fn emit_module_rust(mod_stem: &str, cfg: &ModuleCfg) -> GeneratedModuleFiles {
    let fn_list: Vec<&FunctionUnit> = cfg.functions.values().collect();
    let total_fns = fn_list.len();
    let mut total_blocks = 0usize;
    for f in &fn_list {
        total_blocks += f.blocks.len();
    }

    let mut files = Vec::new();
    let mut shard_names = Vec::new();

    for (shard_idx, chunk) in fn_list.chunks(FUNCTIONS_PER_SHARD).enumerate() {
        let shard_stem = format!("{mod_stem}_s{shard_idx}");
        let mut src = String::with_capacity(chunk.len() * 768);
        let _ = writeln!(
            src,
            "// Auto-generated by DSRecomp (`nitro-lifter`) — DO NOT EDIT."
        );
        let _ = writeln!(
            src,
            "#![allow(clippy::all, unused_variables, unused_mut, unreachable_code)]"
        );
        let _ = writeln!(
            src,
            "use nitro_runtime::{{AotDispatchFn, CpuContext, NitroBus}};\n"
        );

        for func in chunk {
            emit_function(&mut src, func);
        }

        // Emit per-shard block/entry dispatcher
        let _ = writeln!(
            src,
            "pub fn dispatch_shard(pc: u32, thumb: bool, cpu: &mut CpuContext, bus: &mut NitroBus, root_dispatch: AotDispatchFn) -> bool {{"
        );
        let _ = writeln!(src, "    match (pc, thumb) {{");
        for func in chunk {
            let is_thumb = func.entry_mode == CpuMode::Thumb;
            for &blk_addr in func.blocks.keys() {
                let _ = writeln!(
                    src,
                    "        (0x{blk_addr:08X}, {is_thumb}) => {{ {}(cpu, bus, 0x{blk_addr:08X}, root_dispatch); true }}",
                    func.name
                );
            }
        }
        let _ = writeln!(src, "        _ => false,");
        let _ = writeln!(src, "    }}");
        let _ = writeln!(src, "}}");

        files.push((format!("{shard_stem}.rs"), src));
        shard_names.push(shard_stem);
    }

    // Emit top-level module router (`{mod_stem}.rs`)
    let mut hub = String::new();
    let _ = writeln!(
        hub,
        "// Auto-generated module router for `{}` ({} functions, {} blocks).",
        cfg.module_name, total_fns, total_blocks
    );
    let _ = writeln!(
        hub,
        "use nitro_runtime::{{AotDispatchFn, CpuContext, NitroBus}};\n"
    );
    for s in &shard_names {
        let _ = writeln!(hub, "#[path = \"{s}.rs\"]\nmod {s};");
    }
    let _ = writeln!(
        hub,
        "\npub fn dispatch(pc: u32, thumb: bool, cpu: &mut CpuContext, bus: &mut NitroBus, root_dispatch: AotDispatchFn) -> bool {{"
    );
    for s in &shard_names {
        let _ = writeln!(
            hub,
            "    if {s}::dispatch_shard(pc, thumb, cpu, bus, root_dispatch) {{ return true; }}"
        );
    }
    let _ = writeln!(hub, "    false");
    let _ = writeln!(hub, "}}");

    files.push((format!("{mod_stem}.rs"), hub));

    GeneratedModuleFiles {
        files,
        mod_stem: mod_stem.to_string(),
        function_count: total_fns,
        block_count: total_blocks,
    }
}

fn emit_function(out: &mut String, func: &FunctionUnit) {
    let is_thumb = func.entry_mode == CpuMode::Thumb;
    let _ = writeln!(
        out,
        "pub fn {}(cpu: &mut CpuContext, bus: &mut NitroBus, mut block_pc: u32, root_dispatch: AotDispatchFn) {{",
        func.name
    );
    let _ = writeln!(out, "    cpu.thumb = {is_thumb};");
    let _ = writeln!(out, "    loop {{");
    let _ = writeln!(out, "        cpu.aot_blocks_executed += 1;");
    let _ = writeln!(out, "        match block_pc {{");

    for (&blk_addr, blk) in &func.blocks {
        let _ = writeln!(out, "            0x{blk_addr:08X} => {{");
        let inst_count = blk.instructions.len();
        for (idx, inst) in blk.instructions.iter().enumerate() {
            let is_last = idx + 1 == inst_count;
            emit_instruction(out, func, inst);
            if is_last {
                // If the last instruction wasn't an unconditional return/continue, emit fallthrough!
                if !inst.is_unconditional_terminator() {
                    let fallthrough = blk
                        .outgoing
                        .iter()
                        .find(|e| matches!(e.kind, EdgeKind::Fallthrough));
                    if let Some(ft) = fallthrough {
                        if ft.mode == func.entry_mode && func.blocks.contains_key(&ft.target) {
                            let _ = writeln!(
                                out,
                                "                block_pc = 0x{:08X}; continue;",
                                ft.target
                            );
                        } else {
                            let ft_thumb = ft.mode == CpuMode::Thumb;
                            let _ = writeln!(
                                out,
                                "                cpu.regs[15] = 0x{:08X}; cpu.thumb = {ft_thumb}; return;",
                                ft.target
                            );
                        }
                    } else {
                        let next_pc = inst.addr.wrapping_add(u32::from(inst.size));
                        let _ = writeln!(
                            out,
                            "                cpu.regs[15] = 0x{next_pc:08X}; cpu.thumb = {is_thumb}; return;"
                        );
                    }
                }
            }
        }
        let _ = writeln!(out, "            }}");
    }

    let _ = writeln!(
        out,
        "            other => {{ cpu.regs[15] = other; cpu.thumb = {is_thumb}; return; }}"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}\n");
}

fn emit_instruction(out: &mut String, func: &FunctionUnit, inst: &DecodedInst) {
    let next_pc = inst.addr.wrapping_add(u32::from(inst.size));
    let is_thumb = inst.mode == CpuMode::Thumb;
    let pad = if inst.cond == Cond::Al {
        "                "
    } else {
        let _ = writeln!(
            out,
            "                if cpu.check_cond({}) {{",
            inst.cond as u8
        );
        "                    "
    };

    let _ = writeln!(
        out,
        "{pad}cpu.step_tick(1); // 0x{:08X}: {}",
        inst.addr, inst
    );

    match inst.op {
        ArmOp::Nop => {}
        ArmOp::Alu {
            op,
            rd,
            rn,
            rhs,
            set_flags,
        } => {
            let rn_expr = reg_or_pc_expr(rn, inst, false);
            let (rhs_expr, carry_expr) = op2_expr(rhs, inst, set_flags);
            let _ = writeln!(
                out,
                "{pad}if let Some(res) = cpu.exec_alu({}, {rn_expr}, {rhs_expr}, {carry_expr}, {set_flags}) {{",
                op as u8
            );
            if rd == 15 {
                let _ = writeln!(out, "{pad}    cpu.write_pc_alu(res); return;");
            } else {
                let _ = writeln!(out, "{pad}    cpu.regs[{rd}] = res;");
            }
            let _ = writeln!(out, "{pad}}}");
        }
        ArmOp::Mul {
            accumulate,
            rd,
            rm,
            rs,
            rn,
            set_flags,
        } => {
            let _ = writeln!(
                out,
                "{pad}cpu.exec_mul({accumulate}, {rd}, {rm}, {rs}, {rn}, {set_flags});"
            );
        }
        ArmOp::Mull {
            signed,
            accumulate,
            rd_hi,
            rd_lo,
            rm,
            rs,
            set_flags,
        } => {
            let _ = writeln!(
                out,
                "{pad}cpu.exec_mull({signed}, {accumulate}, {rd_hi}, {rd_lo}, {rm}, {rs}, {set_flags});"
            );
        }
        ArmOp::Clz { rd, rm } => {
            let _ = writeln!(out, "{pad}cpu.regs[{rd}] = cpu.regs[{rm}].leading_zeros();");
        }
        ArmOp::Branch {
            target,
            link: true,
            exchange_to,
        } => {
            let callee_mode = exchange_to.unwrap_or(inst.mode);
            let callee_thumb = callee_mode == CpuMode::Thumb;
            let aligned_target = if callee_thumb {
                target & !1
            } else {
                target & !3
            };
            let ret_lr = if is_thumb { next_pc | 1 } else { next_pc };
            let _ = writeln!(out, "{pad}cpu.regs[14] = 0x{ret_lr:08X};");
            let _ = writeln!(
                out,
                "{pad}nitro_runtime::call_direct(cpu, bus, root_dispatch, 0x{aligned_target:08X}, {callee_thumb}, 0x{next_pc:08X}, {is_thumb});"
            );
            let _ = writeln!(
                out,
                "{pad}if cpu.should_break_aot(0x{next_pc:08X}, {is_thumb}) {{ return; }}"
            );
        }
        ArmOp::Branch {
            target,
            link: false,
            exchange_to,
        } => {
            let dst_mode = exchange_to.unwrap_or(inst.mode);
            let dst_thumb = dst_mode == CpuMode::Thumb;
            let aligned_target = if dst_thumb { target & !1 } else { target & !3 };
            if dst_mode == func.entry_mode && func.blocks.contains_key(&aligned_target) {
                if aligned_target <= inst.addr {
                    let _ = writeln!(
                        out,
                        "{pad}if cpu.should_yield_frame() {{ cpu.regs[15] = 0x{aligned_target:08X}; cpu.thumb = {dst_thumb}; return; }}"
                    );
                }
                let _ = writeln!(out, "{pad}block_pc = 0x{aligned_target:08X}; continue;");
            } else {
                let _ = writeln!(
                    out,
                    "{pad}cpu.regs[15] = 0x{aligned_target:08X}; cpu.thumb = {dst_thumb}; return;"
                );
            }
        }
        ArmOp::BranchExchangeReg { rm, link } => {
            if link {
                let ret_lr = if is_thumb { next_pc | 1 } else { next_pc };
                let _ = writeln!(out, "{pad}let target = cpu.regs[{rm}];");
                let _ = writeln!(out, "{pad}cpu.regs[14] = 0x{ret_lr:08X};");
                let _ = writeln!(
                    out,
                    "{pad}nitro_runtime::call_indirect(cpu, bus, root_dispatch, target, 0x{next_pc:08X}, {is_thumb});"
                );
                let _ = writeln!(
                    out,
                    "{pad}if cpu.should_break_aot(0x{next_pc:08X}, {is_thumb}) {{ return; }}"
                );
            } else {
                let _ = writeln!(out, "{pad}let target = cpu.regs[{rm}];");
                let _ = writeln!(out, "{pad}cpu.write_pc_interworking(target); return;");
            }
        }
        ArmOp::MemSingle {
            load,
            size,
            rd,
            rn,
            offset,
            pre_index,
            writeback,
            thumb_pc_align,
        } => {
            let base_expr = reg_or_pc_expr(rn, inst, thumb_pc_align);
            let off_expr = addr_offset_expr(offset, inst);
            let size_code: u8 = match size {
                MemSize::Word => 0,
                MemSize::Halfword => 1,
                MemSize::SignedHalfword => 2,
                MemSize::Byte => 3,
                MemSize::SignedByte => 4,
                MemSize::Doubleword => 5,
            };
            let _ = writeln!(
                out,
                "{pad}if nitro_runtime::exec_mem_single(cpu, bus, {load}, {size_code}, {rd}, {rn}, {base_expr}, {off_expr}, {pre_index}, {writeback}) {{ return; }}"
            );
        }
        ArmOp::MemMultiple {
            load,
            rn,
            reg_mask,
            increment,
            before,
            writeback,
            ..
        } => {
            let _ = writeln!(
                out,
                "{pad}if nitro_runtime::exec_mem_multiple(cpu, bus, {load}, {rn}, 0x{reg_mask:04X}, {increment}, {before}, {writeback}) {{ return; }}"
            );
        }
        ArmOp::Mrs { rd, spsr } => {
            let _ = writeln!(out, "{pad}cpu.regs[{rd}] = cpu.read_psr({spsr});");
        }
        ArmOp::Msr { spsr, mask, rhs } => {
            let (val_expr, _) = op2_expr(rhs, inst, false);
            let _ = writeln!(out, "{pad}cpu.write_psr({spsr}, {mask}, {val_expr});");
        }
        ArmOp::Swp { byte, rd, rm, rn } => {
            let _ = writeln!(
                out,
                "{pad}nitro_runtime::exec_swp(cpu, bus, {byte}, {rd}, {rm}, {rn});"
            );
        }
        ArmOp::Swi { comment } => {
            let _ = writeln!(
                out,
                "{pad}cpu.regs[15] = 0x{next_pc:08X}; cpu.thumb = {is_thumb};"
            );
            let _ = writeln!(out, "{pad}bus.swi_hle(cpu, 0x{comment:X});");
            let _ = writeln!(
                out,
                "{pad}if cpu.halted || cpu.vblank_requested {{ return; }}"
            );
        }
        ArmOp::CoprocMove {
            to_coproc,
            cp,
            op1,
            rd,
            crn,
            crm,
            op2,
        } => {
            let _ = writeln!(
                out,
                "{pad}bus.coproc_move(cpu, {to_coproc}, {cp}, {op1}, {rd}, {crn}, {crm}, {op2});"
            );
            let _ = writeln!(
                out,
                "{pad}if cpu.halted || cpu.vblank_requested {{ cpu.regs[15] = 0x{next_pc:08X}; return; }}"
            );
        }
        ArmOp::Unknown { .. } => {
            let _ = writeln!(
                out,
                "{pad}cpu.regs[15] = 0x{:08X}; cpu.thumb = {is_thumb}; return;",
                inst.addr
            );
        }
    }

    if inst.cond != Cond::Al {
        let _ = writeln!(out, "                }}");
    }
}

fn reg_or_pc_expr(reg: u8, inst: &DecodedInst, align_word: bool) -> String {
    if reg == 15 {
        let mut pc = inst.pc_read_value();
        if align_word {
            pc &= !3;
        }
        format!("0x{pc:08X}u32")
    } else {
        format!("cpu.regs[{reg}]")
    }
}

fn shift_code(s: ShiftOp) -> u8 {
    match s {
        ShiftOp::Lsl => 0,
        ShiftOp::Lsr => 1,
        ShiftOp::Asr => 2,
        ShiftOp::Ror => 3,
        ShiftOp::Rrx => 4,
    }
}

fn op2_expr(op2: ShiftedOp2, inst: &DecodedInst, need_carry: bool) -> (String, String) {
    match op2 {
        ShiftedOp2::Imm { value, rot_carry } => {
            let c_expr = match rot_carry {
                Some(b) => b.to_string(),
                None => "cpu.c".to_string(),
            };
            (format!("0x{value:08X}u32"), c_expr)
        }
        ShiftedOp2::RegImm {
            rm,
            shift: ShiftOp::Lsl,
            amount: 0,
        } => (reg_or_pc_expr(rm, inst, false), "cpu.c".to_string()),
        ShiftedOp2::RegImm { rm, shift, amount } => {
            let rm_e = reg_or_pc_expr(rm, inst, false);
            let sc = shift_code(shift);
            if need_carry {
                (
                    format!("cpu.shift_imm_val({rm_e}, {sc}, {amount})"),
                    format!("cpu.shift_imm_carry({rm_e}, {sc}, {amount})"),
                )
            } else {
                (
                    format!("cpu.shift_imm_val({rm_e}, {sc}, {amount})"),
                    "cpu.c".to_string(),
                )
            }
        }
        ShiftedOp2::RegReg { rm, shift, rs } => {
            let rm_e = reg_or_pc_expr(rm, inst, false);
            let rs_e = reg_or_pc_expr(rs, inst, false);
            let sc = shift_code(shift);
            if need_carry {
                (
                    format!("cpu.shift_reg_val({rm_e}, {sc}, {rs_e})"),
                    format!("cpu.shift_reg_carry({rm_e}, {sc}, {rs_e})"),
                )
            } else {
                (
                    format!("cpu.shift_reg_val({rm_e}, {sc}, {rs_e})"),
                    "cpu.c".to_string(),
                )
            }
        }
    }
}

fn addr_offset_expr(offset: AddrOffset, inst: &DecodedInst) -> String {
    match offset {
        AddrOffset::Imm(imm) => format!("{imm}i32"),
        AddrOffset::Reg {
            rm,
            shift,
            amount,
            add,
        } => {
            let rm_e = reg_or_pc_expr(rm, inst, false);
            let shifted = if matches!(shift, ShiftOp::Lsl) && amount == 0 {
                rm_e
            } else {
                format!("cpu.shift_imm_val({rm_e}, {}, {amount})", shift_code(shift))
            };
            if add {
                format!("({shifted} as i32)")
            } else {
                format!("-({shifted} as i32)")
            }
        }
    }
}
